// Static score-vector names avoid dynamic arrays; retain exact reductions.
// Register allocation may still spill under Gaudi2 register pressure.
void main(tensor logits,tensor mask,tensor sink,tensor scale,tensor probabilities) {
const int5 start=get_index_space_offset(),end=start+get_index_space_size();
const float factor=s_f32_ld_g(gen_addr((int5){0},scale));
for(int token=start[1];token<end[1];++token) {
for(int head=start[0];head<end[0];++head) {
const float sink_value=s_f32_ld_g(gen_addr((int5){head},sink));
float64 maximum=sink_value;
const bool64 v0=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){0,token},mask),0.0f);
float64 s0=v_f32_ld_tnsr_b((int5){0,head,token},logits)*factor;
s0=v_f32_mov_vb(s0,0,-3.402823466e+38f,v0,0);
maximum=v_f32_max_b(maximum,s0);
const bool64 v1=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){64,token},mask),0.0f);
float64 s1=v_f32_ld_tnsr_b((int5){64,head,token},logits)*factor;
s1=v_f32_mov_vb(s1,0,-3.402823466e+38f,v1,0);
maximum=v_f32_max_b(maximum,s1);
const bool64 v2=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){128,token},mask),0.0f);
float64 s2=v_f32_ld_tnsr_b((int5){128,head,token},logits)*factor;
s2=v_f32_mov_vb(s2,0,-3.402823466e+38f,v2,0);
maximum=v_f32_max_b(maximum,s2);
const bool64 v3=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){192,token},mask),0.0f);
float64 s3=v_f32_ld_tnsr_b((int5){192,head,token},logits)*factor;
s3=v_f32_mov_vb(s3,0,-3.402823466e+38f,v3,0);
maximum=v_f32_max_b(maximum,s3);
const bool64 v4=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){256,token},mask),0.0f);
float64 s4=v_f32_ld_tnsr_b((int5){256,head,token},logits)*factor;
s4=v_f32_mov_vb(s4,0,-3.402823466e+38f,v4,0);
maximum=v_f32_max_b(maximum,s4);
const bool64 v5=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){320,token},mask),0.0f);
float64 s5=v_f32_ld_tnsr_b((int5){320,head,token},logits)*factor;
s5=v_f32_mov_vb(s5,0,-3.402823466e+38f,v5,0);
maximum=v_f32_max_b(maximum,s5);
const bool64 v6=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){384,token},mask),0.0f);
float64 s6=v_f32_ld_tnsr_b((int5){384,head,token},logits)*factor;
s6=v_f32_mov_vb(s6,0,-3.402823466e+38f,v6,0);
maximum=v_f32_max_b(maximum,s6);
const bool64 v7=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){448,token},mask),0.0f);
float64 s7=v_f32_ld_tnsr_b((int5){448,head,token},logits)*factor;
s7=v_f32_mov_vb(s7,0,-3.402823466e+38f,v7,0);
maximum=v_f32_max_b(maximum,s7);
const bool64 v8=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){512,token},mask),0.0f);
float64 s8=v_f32_ld_tnsr_b((int5){512,head,token},logits)*factor;
s8=v_f32_mov_vb(s8,0,-3.402823466e+38f,v8,0);
maximum=v_f32_max_b(maximum,s8);
const bool64 v9=v_f32_cmp_grt_b(v_f32_ld_tnsr_b((int5){576,token},mask),0.0f);
float64 s9=v_f32_ld_tnsr_b((int5){576,head,token},logits)*factor;
s9=v_f32_mov_vb(s9,0,-3.402823466e+38f,v9,0);
maximum=v_f32_max_b(maximum,s9);
maximum=v_f32_reduce_max(maximum);
float64 total=0;
float64 e0=v_exp_cephes_f32(s0-maximum);
e0=v_f32_mov_vb(e0,0,0,v0,0);
total+=e0;
float64 e1=v_exp_cephes_f32(s1-maximum);
e1=v_f32_mov_vb(e1,0,0,v1,0);
total+=e1;
float64 e2=v_exp_cephes_f32(s2-maximum);
e2=v_f32_mov_vb(e2,0,0,v2,0);
total+=e2;
float64 e3=v_exp_cephes_f32(s3-maximum);
e3=v_f32_mov_vb(e3,0,0,v3,0);
total+=e3;
float64 e4=v_exp_cephes_f32(s4-maximum);
e4=v_f32_mov_vb(e4,0,0,v4,0);
total+=e4;
float64 e5=v_exp_cephes_f32(s5-maximum);
e5=v_f32_mov_vb(e5,0,0,v5,0);
total+=e5;
float64 e6=v_exp_cephes_f32(s6-maximum);
e6=v_f32_mov_vb(e6,0,0,v6,0);
total+=e6;
float64 e7=v_exp_cephes_f32(s7-maximum);
e7=v_f32_mov_vb(e7,0,0,v7,0);
total+=e7;
float64 e8=v_exp_cephes_f32(s8-maximum);
e8=v_f32_mov_vb(e8,0,0,v8,0);
total+=e8;
float64 e9=v_exp_cephes_f32(s9-maximum);
e9=v_f32_mov_vb(e9,0,0,v9,0);
total+=e9;
total=v_f32_reduce_add(total)+v_exp_cephes_f32(sink_value-maximum);
float64 inverse=v_reciprocal_f32(total);
inverse=inverse*(2.0f-total*inverse);
v_f32_st_tnsr((int5){0,head,token},probabilities,e0*inverse);
v_f32_st_tnsr((int5){64,head,token},probabilities,e1*inverse);
v_f32_st_tnsr((int5){128,head,token},probabilities,e2*inverse);
v_f32_st_tnsr((int5){192,head,token},probabilities,e3*inverse);
v_f32_st_tnsr((int5){256,head,token},probabilities,e4*inverse);
v_f32_st_tnsr((int5){320,head,token},probabilities,e5*inverse);
v_f32_st_tnsr((int5){384,head,token},probabilities,e6*inverse);
v_f32_st_tnsr((int5){448,head,token},probabilities,e7*inverse);
v_f32_st_tnsr((int5){512,head,token},probabilities,e8*inverse);
v_f32_st_tnsr((int5){576,head,token},probabilities,e9*inverse);
}}}
